
public class DataTypes {
    public static void main(String[] args) {

        int maxAge=Integer.MAX_VALUE;
        int minAge=Integer.MIN_VALUE;
        int byteData=Integer.BYTES;
        System.out.println("Max int is "+maxAge);
        System.out.println("Min int is "+minAge);
        System.out.println("Byte data is "+byteData);

        System.out.println("-----------------------------");
        System.out.println("Max long is "+Long.MAX_VALUE);
        System.out.println("Min long is "+Long.MIN_VALUE);  
        System.out.println("Long byte data is "+ Long.BYTES);  
    }
}

