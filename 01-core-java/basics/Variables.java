package basics;

public class Variables {
    public static void main(String[] args){
        int String=10;
        System.out.println("Age is "+String);
        int age=20;
        System.out.println("Age is "+age);
        //here 20 and 10 is a integer literal
        String name="Robin";
        System.out.println("Name is "+name);
        // String is a class, name is the reference and "Robin" is a string literal or 
        // an object of String class
    }
}

// ABove will work because String is a valid identifier in Java. However, it is not recommended to use reserved keywords or class names as variable names, as it can lead to confusion and make the code less readable.  