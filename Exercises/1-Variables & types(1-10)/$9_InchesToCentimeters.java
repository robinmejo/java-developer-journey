/*
Write a Java program to convert inches into centimeters.
1 inch= 2.54 cm
*/

public class $9_InchesToCentimeters {
    public static void main(String[] args) {
        double inches = 10;
        double centimeters=inches*2.54;
        System.out.println("Centimeters: " + centimeters);
        
    }
}